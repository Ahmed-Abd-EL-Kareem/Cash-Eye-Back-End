export const countUsage = async (filter) => {
  return AIUsageModel.countDocuments(filter);
};

/**
 * Get aggregated dashboard statistics
 * @returns {Promise<Object>}
 */
export const getDashboardStats = async () => {
  const startOfToday = new Date();
  startOfToday.setHours(0, 0, 0, 0);

  const [totalAITrips, totalRequests, requestsToday, stats] = await Promise.all([
    TripModel.countDocuments({ isAIGenerated: true }),
    AIUsageModel.countDocuments(),
    AIUsageModel.countDocuments({ createdAt: { $gte: startOfToday } }),
    AIUsageModel.aggregate([
      {
        $group: {
          _id: null,
          totalTokens: { $sum: "$totalTokens" },
          totalCost: { $sum: "$cost" },
          averageResponseTime: { $avg: "$responseTime" },
          successRequests: {
            $sum: { $cond: [{ $eq: ["$success", true] }, 1, 0] },
          },
        },
      },
    ]),
  ]);

  const aggregateStats = stats[0] || {
    totalTokens: 0,
    totalCost: 0,
    averageResponseTime: 0,
    successRequests: 0,
  };

  const successRate = totalRequests > 0 
    ? (aggregateStats.successRequests / totalRequests) * 100 
    : 100.0;

  return {
    totalAITrips,
    totalRequests,
    totalTokens: aggregateStats.totalTokens,
    totalCost: Number(aggregateStats.totalCost.toFixed(6)),
    averageResponseTime: Number(aggregateStats.averageResponseTime.toFixed(2)),
    successRate: Number(successRate.toFixed(2)),
    requestsToday,
  };
};

/**
 * Get recent AI request logs
 * @param {number} limit 
 * @returns {Promise<Array>}
 */
export const getRecentLogs = async (limit = 10) => {
  return AIUsageModel.find()
    .sort({ createdAt: -1 })
    .limit(limit)
    .populate("user", "name email")
    .populate("trip", "title destination")
    .select("user trip model success cost responseTime createdAt")
    .lean();
};

/**
 * Get top users generating the most AI trips (group by user in successful logs)
 * @param {number} limit 
 * @returns {Promise<Array>}
 */
export const getTopUsers = async (limit = 5) => {
  return AIUsageModel.aggregate([
    { $match: { success: true, trip: { $ne: null } } },
    {
      $group: {
        _id: "$user",
        count: { $sum: 1 },
      },
    },
    { $sort: { count: -1 } },
    { $limit: limit },
    {
      $lookup: {
        from: "users",
        localField: "_id",
        foreignField: "_id",
        as: "userDetails",
      },
    },
    { $unwind: "$userDetails" },
    {
      $project: {
        _id: 0,
        user: {
          _id: "$userDetails._id",
          name: "$userDetails.name",
          email: "$userDetails.email",
        },
        count: 1,
      },
    },
  ]);
};

